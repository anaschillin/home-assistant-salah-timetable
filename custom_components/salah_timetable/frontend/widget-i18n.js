export const WIDGET_CATALOGS = Object.freeze(Object.fromEntries(["en", "ar"].map((language, index) => [
  language, Object.freeze(Object.fromEntries(Object.entries(labels).map(([key, values]) => [key, values[index]]))),
])));

/** Return plain text with the same locale and literal substitution rules as tr(). */
export function widgetTr(ui, key, params = {}) {
  const language = resolveUi({}, {language: typeof ui === "string" ? ui : ui?.language}).language;
  const catalog = WIDGET_CATALOGS[language];
  const own = (object, name) => Object.prototype.hasOwnProperty.call(object, name);
  if (!own(catalog, key) && !own(WIDGET_CATALOGS.en, key)) return tr(ui, key, params);
  const template = own(catalog, key) ? catalog[key] : WIDGET_CATALOGS.en[key];
  return template.replace(/\{([a-zA-Z][a-zA-Z0-9_]*)\}/g, (placeholder, name) => own(params || {}, name) ? String(params[name]) : placeholder);
}
